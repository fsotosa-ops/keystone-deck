    sw = "\n".join(
        f'<div class="sw"><span style="background:var(--ks-{k})"></span>'
        f"<b>{k}</b><code>{v}</code></div>" for k, v in b["color"].items())
    rows = "\n".join(
        f"<tr class=\"{'ok' if r['ok'] else 'bad'}\"><td>{r['fg']}</td><td>{r['bg']}</td>"
        f"<td>{r['size']}</td><td>{r['ratio']}:1</td><td>{r['required']}:1</td>"
        f"<td>{'pass' if r['ok'] else 'FAIL'}</td></tr>" for r in contrast_rows)
